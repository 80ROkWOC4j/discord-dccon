const fs = require('node:fs');
const path = require('node:path');
const {buildSync} = require('esbuild');
const root = path.resolve(__dirname, '..');
const pluginPath = path.join(root, 'artifacts/betterdiscord/discord-dccon.plugin.js');
let splitWorker;
function buildSplitWorker() {
  return splitWorker ??= buildSync({absWorkingDir: root, tsconfigRaw: {}, entryPoints: ['src/core/split-worker.ts'], bundle: true, write: false,
    format: 'esm', platform: 'browser', minify: true, legalComments: 'inline', inject: ['scripts/split-buffer.js'], external: ['fs', 'path', 'util'],
    define: {window: 'globalThis'}}).outputFiles[0].text;
}
function buildOptions() {
  return {absWorkingDir: root, tsconfigRaw: {}, bundle: true, write: false, platform: 'browser', target: 'es2022',
    loader: {'.css': 'text'},
    define: {__DCCON_SPLIT_WORKER__: JSON.stringify(buildSplitWorker()),
      'process.env.NODE_ENV': '"production"'}};
}
function buildEntry(name, options = {}) {
  return buildSync({...buildOptions(), entryPoints: [`src/entries/${name}.ts`], format: 'iife', ...options}).outputFiles[0].text;
}
function writeAtomic(file, source) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === source) return;
  fs.mkdirSync(path.dirname(file), {recursive: true});
  const temporary = `${file}.${process.pid}.tmp`;
  try {fs.writeFileSync(temporary, source); fs.renameSync(temporary, file);}
  finally {fs.rmSync(temporary, {force: true});}
}
function buildBetterDiscord() {
  const version = require('../package.json').version;
  const header = fs.readFileSync(path.join(root, 'src/entries/betterdiscord.header'), 'utf8').replace('__VERSION__', version);
  const source = header + '// Generated from src/entries/betterdiscord.ts. Do not edit this file.\n' + buildEntry('betterdiscord', {format: 'cjs', footer: {js: 'module.exports = module.exports.default;'}});
  writeAtomic(pluginPath, source);
  return source;
}
function buildStorage() {
  return buildSync({absWorkingDir: root, tsconfigRaw: {}, entryPoints: ['src/storage/node.ts'], bundle: true,
    write: false, format: 'cjs', platform: 'node', target: 'es2022'}).outputFiles[0].text;
}
function buildShelterPlugin(version) {
  const bundle = buildEntry('shelter', {globalName: 'DCConShelterEntry'});
  return `(() => {\n${bundle}\nreturn DCConShelterEntry.createShelterPlugin(shelter,globalThis.DCConNative,globalThis.dcconWebpack,${JSON.stringify(version)});\n})()`;
}
module.exports = {root, pluginPath, buildStorage, buildOptions, buildEntry, buildBetterDiscord, buildShelterPlugin, buildSplitWorker, writeAtomic};
if (require.main === module) buildBetterDiscord();
